export type Lang = 'en' | 'ru' | 'uz';

const guess = (): Lang => {
  try {
    const saved = localStorage.getItem('sm-lang');
    if (saved === 'en' || saved === 'ru' || saved === 'uz') return saved;
    const n = (navigator.language || 'en').slice(0, 2);
    if (n === 'ru') return 'ru';
    if (n === 'uz') return 'uz';
  } catch (e) { /* ignore */ }
  return 'en';
};

export let LANG: Lang = guess();
export const setLang = (l: Lang) => {
  LANG = l;
  try { localStorage.setItem('sm-lang', l); } catch (e) { /* ignore */ }
};

